"""Layout value conversion and responsive values."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from shadlet.components.base import ComponentError

Length = int | float | str

BREAKPOINTS = ("base", "sm", "md", "lg", "xl", "xxl")


def css_length(value: Length | None, *, argument: str) -> str | None:
    if value is None:
        return None
    if isinstance(value, bool):
        raise ComponentError(f"{argument} must be a length, not a boolean")
    if isinstance(value, (int, float)):
        return f"{value:g}px"
    if isinstance(value, str):
        if not value.strip():
            raise ComponentError(f"{argument} cannot be an empty string")
        return value
    raise ComponentError(f"{argument} must be a number (pixels) or CSS length string")


def css_spacing(
    value: Length | tuple[Length, ...] | list[Length] | None, *, argument: str
) -> str | None:
    if value is None:
        return None
    if isinstance(value, (list, tuple)):
        if not 1 <= len(value) <= 4:
            raise ComponentError(f"{argument} accepts 1 to 4 values")
        parts = [css_length(item, argument=argument) for item in value]
        return " ".join(part for part in parts if part is not None)
    return css_length(value, argument=argument)


def css_number(value: float | None, *, argument: str) -> str | None:
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ComponentError(f"{argument} must be a number")
    return f"{value:g}"


def set_style(style: dict[str, Any], key: str, value: Any) -> None:
    if value is not None:
        style[key] = value


@dataclass(frozen=True, slots=True)
class Responsive:
    """Responsive integer values for grid tracks.

    ``base`` applies at every width; each larger breakpoint overrides the
    previous one through CSS media queries generated by the renderer.
    """

    base: int
    sm: int | None = None
    md: int | None = None
    lg: int | None = None
    xl: int | None = None
    xxl: int | None = None

    def __post_init__(self) -> None:
        for name in BREAKPOINTS:
            value = getattr(self, name)
            if value is not None and (
                not isinstance(value, int) or isinstance(value, bool) or value < 1
            ):
                raise ComponentError(f"Responsive.{name} must be a positive integer")

    def to_wire(self) -> dict[str, int]:
        result = {"base": self.base}
        for name in BREAKPOINTS[1:]:
            value = getattr(self, name)
            if value is not None:
                result["2xl" if name == "xxl" else name] = value
        return result


def grid_tracks(
    value: int | Responsive | None, *, argument: str
) -> int | dict[str, int] | None:
    if value is None:
        return None
    if isinstance(value, Responsive):
        return value.to_wire()
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise ComponentError(f"{argument} must be a positive integer or Responsive")
    return value


__all__ = [
    "BREAKPOINTS",
    "Length",
    "Responsive",
    "css_length",
    "css_number",
    "css_spacing",
    "grid_tracks",
    "set_style",
]
